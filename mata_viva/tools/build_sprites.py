"""Build the Godot sprite assets from Pixelwright renders.

The art lives in the Pixelwright project "Mata Viva". Each animation was rendered with
render_preview (zoom 1, background "none"), which gives a filmstrip PNG: frames left to
right, top to bottom, a 1 px gap between columns and a 21 px frame-number band above each
row. This script slices those strips (tools/slice_strip.py), writes one horizontal strip per
animation to assets/sprites/ and regenerates scripts/sprite_db.gd (sizes, frame counts,
durations in ms and loop flags) from tools/pixelwright_manifest.json.

Usage: python3 tools/build_sprites.py <folder with the Pixelwright renders> [project dir]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from slice_strip import slice_strip  # noqa: E402
from PIL import Image  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def main(renders, project):
    RESULTS = renders
    man = json.load(open(os.path.join(HERE, 'pixelwright_manifest.json')))
    out_dir = os.path.join(project, 'assets', 'sprites')
    os.makedirs(out_dir, exist_ok=True)
    db = {}
    for name, spec in man.items():
        if name == 'singles':
            continue
        w, h = spec['w'], spec['h']
        entry = {'w': w, 'h': h, 'anims': {}}
        for anim, a in spec['anims'].items():
            frames = slice_strip(os.path.join(RESULTS, a['strip']), w, h, a['n'])
            strip = Image.new('RGBA', (w * len(frames), h), (0, 0, 0, 0))
            for i, f in enumerate(frames):
                strip.paste(f, (i * w, 0))
            fn = f'{name}_{anim}.png'
            strip.save(os.path.join(out_dir, fn))
            entry['anims'][anim] = {'tex': f'res://assets/sprites/{fn}', 'n': len(frames), 'ms': a['ms'], 'loop': a['loop']}
        db[name] = entry
    singles = {}
    for name, fn in man['singles'].items():
        im = Image.open(os.path.join(RESULTS, fn)).convert('RGBA')
        im.save(os.path.join(out_dir, f'{name}.png'))
        singles[name] = {'tex': f'res://assets/sprites/{name}.png', 'w': im.size[0], 'h': im.size[1]}

    def gd(v, ind=1):
        pad = '\t' * ind
        if isinstance(v, dict):
            items = [f'{pad}"{k}": {gd(x, ind + 1)}' for k, x in v.items()]
            return '{\n' + ',\n'.join(items) + '\n' + '\t' * (ind - 1) + '}'
        if isinstance(v, bool):
            return 'true' if v else 'false'
        if isinstance(v, list):
            return '[' + ', '.join(str(x) for x in v) + ']'
        if isinstance(v, str):
            return f'"{v}"'
        return str(v)

    os.makedirs(os.path.join(project, 'scripts'), exist_ok=True)
    with open(os.path.join(project, 'scripts', 'sprite_db.gd'), 'w') as f:
        f.write('# Generated by tools/build_sprites.py from the Pixelwright project "Mata Viva".\n')
        f.write('# Do not edit by hand: re-run the build after changing the art.\n')
        f.write('class_name SpriteDB\nextends RefCounted\n\n')
        f.write('const ANIMS := ' + gd(db) + '\n\n')
        f.write('const SINGLES := ' + gd(singles) + '\n')
    print('sprites:', sorted(os.listdir(out_dir)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(HERE))
